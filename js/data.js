/**
 * Computes current open/closed state in Asia/Tehran for a club's schedule.
 * @param {object} hours
 * @param {Date} [nowDate]
 */
export function getClubOpenStatus(hours, nowDate = new Date()) {
  if (!hours) return { known: false, isOpen: false, label: 'ساعات نامشخص', todayRange: 'ثبت نشده' };
  const tehranStr = nowDate.toLocaleString('en-US', { timeZone: 'Asia/Tehran', hour12: false, weekday: 'short', hour: '2-digit', minute: '2-digit' });
  // tehranStr looks like "Sat, 14:25" or similar
  const dayMap = { Sat: 'sat', Sun: 'sun', Mon: 'mon', Tue: 'tue', Wed: 'wed', Thu: 'thu', Fri: 'fri' };
  const parts = tehranStr.split(',').map((s) => s.trim());
  const dayKey = dayMap[parts[0]] || 'sat';
  const timePart = parts[1] || '12:00';
  const [hh, mm] = timePart.split(':').map((n) => parseInt(n, 10));
  const nowMinutes = (isNaN(hh) ? 12 : hh) * 60 + (isNaN(mm) ? 0 : mm);

  const schedule = hours[dayKey];
  if (!schedule || schedule.open === 'closed' || schedule.close === 'closed') {
    return { known: true, isOpen: false, label: 'امروز تعطیل', todayRange: 'تعطیل' };
  }
  const [oh, om] = schedule.open.split(':').map(Number);
  const [ch, cm] = schedule.close.split(':').map(Number);
  const openMin = oh * 60 + om;
  const closeMin = ch * 60 + cm;
  const isOpen = nowMinutes >= openMin && nowMinutes < closeMin;
  return {
    known: true,
    isOpen,
    label: isOpen ? 'اکنون باز است' : 'اکنون بسته است',
    todayRange: `${schedule.open} تا ${schedule.close}`,
    note: schedule.note || '',
  };
}
